#!/usr/bin/env python3
"""Exercise the independent Auth and business APIs in a disposable Compose project."""
import concurrent.futures
import importlib.util
import json
import os
from pathlib import Path
import secrets
import subprocess
import tempfile
import urllib.error
import urllib.request

spec = importlib.util.spec_from_file_location("events", Path(__file__).with_name("verify-events.py"))
e = importlib.util.module_from_spec(spec)
spec.loader.exec_module(e)
e.COMPOSE[e.COMPOSE.index("food-events-e2e")] = "food-auth-service-e2e"
e.COMPOSE += ["-f", str(e.ROOT / "deploy/compose.auth.yaml")]
ORIGIN = "http://localhost:9000"


def send(port, path, method="GET", body=None, token=None, cookie=None, csrf=None, expected=200, origin=ORIGIN):
    headers = {"Content-Type": "application/json"}
    if origin:
        headers["Origin"] = origin
    if token:
        headers["Authorization"] = "Bearer " + token
    if cookie:
        headers["Cookie"] = cookie
    if csrf:
        headers["X-CSRF-Token"] = csrf
    req = urllib.request.Request(f"http://localhost:{port}{path}", method=method,
                                 data=None if body is None else json.dumps(body).encode(), headers=headers)
    try:
        response = urllib.request.urlopen(req, timeout=15)
    except urllib.error.HTTPError as error:
        response = error
    with response:
        # Bodies and credentials must never appear in failure output.
        assert response.status == expected, f"{method} {port}{path}: {response.status}, expected {expected}"
        raw = response.read()
        return (json.loads(raw) if raw else None), response.headers


def provision(data):
    subprocess.run(e.COMPOSE + ["exec", "-T", "auth", "authctl", "provision", "-operator", "stage18-test-admin"],
                   cwd=e.ROOT, env=e.ENV, input=json.dumps(data), text=True, check=True,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def login(email, password):
    value, headers = send(28084, "/v1/auth/login", "POST", {"email": email, "password": password})
    return value, headers["Set-Cookie"].split(";", 1)[0]


def main():
    with tempfile.TemporaryDirectory(prefix="food-auth-stage18-") as directory:
        root = Path(directory)
        for name in ("service.key", "csrf.key"):
            (root / name).write_text(secrets.token_urlsafe(48))
        # Disposable fixture secrets only; host parent remains mode 0700.
        (root / "keys.json").touch()
        e.ENV.update(AUTH_DEV_DIR=str(root), AUTH_POSTGRES_PASSWORD=secrets.token_hex(24),
                     AUTH_DB_PASSWORD=secrets.token_hex(24), AUTH_PORT="28084", AUTH_ISSUER="http://localhost:28084",
                     AUTH_COOKIE_SECURE="false", AUTH_ALLOW_UNVERIFIED_LOGIN="true", AUTH_ACTIVE_KID="initial",
                     CORS_ALLOWED_ORIGINS=ORIGIN, PUSH_PROVIDER="fake", DEV_AUTH_ENABLED="false")
        password = secrets.token_urlsafe(32)
        try:
            e.compose("build", "auth")
            e.compose("run", "--rm", "--no-deps", "--user", "0:0", "--entrypoint", "authctl",
                      "-v", f"{root}:/fixture", "auth", "keygen", "-out", "/fixture/new-keys.json", "-kid", "initial")
            # The key generated by a root container is readable inside this isolated fixture.
            e.compose("run", "--rm", "--no-deps", "--user", "0:0", "--entrypoint", "chmod",
                      "-v", f"{root}:/fixture", "auth", "644", "/fixture/new-keys.json")
            (root / "keys.json").write_bytes((root / "new-keys.json").read_bytes())
            e.compose("up", "--build", "-d", "--wait", "--wait-timeout", "240")
            registry = {"issuer": "https://legacy.example/realms/food", "identities": [
                {"subject": "legacy-staff", "user_id": 10, "roles": ["restaurant_staff"], "restaurants": [1]},
                {"subject": "legacy-customer", "user_id": 101, "customer_id": 7, "roles": ["customer"]},
                {"subject": "legacy-courier", "user_id": 103, "courier_id": 1, "roles": ["courier"]}]}
            (root / "registry.json").write_text(json.dumps(registry))
            for _ in range(2):
                e.compose("run", "--rm", "--no-deps", "--entrypoint", "authctl", "-v", f"{root / 'registry.json'}:/registry.json:ro",
                          "auth", "import-registry", "-registry", "/registry.json", "-operator", "stage18-migration")
            provision({"email": "admin@example.test", "password": password, "roles": ["admin", "dispatcher"],
                       "permissions": ["delivery:dispatch", "saga:retry"], "restaurant_ids": [1]})
            provision({"user_id": 10, "email": "staff@example.test", "password": password,
                       "roles": ["restaurant_staff"], "restaurant_ids": [1]})
            admin, _ = login("admin@example.test", password)
            staff, _ = login("staff@example.test", password)
            at, st = admin["access_token"], staff["access_token"]
            assert staff["user"]["user_id"] == 10 and staff["user"]["restaurant_ids"] == [1]
            assert staff["user"]["email_verified_at"] is None
            profile, _ = send(28081, "/v1/auth/me", token=st)
            assert profile["user_id"] == 10 and profile["restaurant_ids"] == [1]
            send(28080, "/restaurants/1", "PATCH", {"name": "Stage 18"}, token=st)
            send(28081, "/restaurants/1/orders", token=st)
            send(28085, "/couriers", token=at)
            send(28083, "/v1/devices", token=st)
            device, _ = send(28083, "/v1/devices", "POST", {"owner_type": "RESTAURANT", "restaurant_id": 1,
                                                             "platform": "WEB", "installation_id": "stage18-fake-installation"}, token=st)
            # The same response is used for a fresh registration and a duplicate.
            signup = {"email": "customer@example.test", "password": password}
            for _ in range(2):
                send(28084, "/v1/auth/register", "POST", signup, expected=202)
            send(28084, "/v1/auth/register", "POST", {**signup, "roles": ["admin"]}, expected=400)
            customer, cookie = login(signup["email"], password)
            ct = customer["access_token"]
            assert customer["user"]["roles"] == ["customer"] and customer["user"]["restaurant_ids"] == []
            send(28084, "/v1/auth/me", token=ct)
            send(28081, "/v1/auth/me", token=ct)
            send(28085, "/couriers", token=ct, expected=403)
            send(28084, "/v1/auth/admin/users/10/bindings", "PUT", {"roles": ["admin"]}, token=ct, expected=403)
            send(28084, "/v1/auth/login", "POST", {**signup, "password": "wrong password"}, expected=401)
            send(28084, "/v1/auth/refresh", "POST", {}, cookie=cookie, expected=403)
            send(28084, "/v1/auth/refresh", "POST", {}, cookie=cookie, csrf=customer["csrf_token"],
                 origin="https://evil.example", expected=403)
            rotated, headers = send(28084, "/v1/auth/refresh", "POST", {}, cookie=cookie, csrf=customer["csrf_token"])
            fresh_cookie = headers["Set-Cookie"].split(";", 1)[0]
            assert fresh_cookie != cookie
            send(28084, "/v1/auth/refresh", "POST", {}, cookie=cookie, csrf=customer["csrf_token"], expected=401)
            send(28081, "/v1/auth/me", token=rotated["access_token"], expected=401)
            customer, cookie = login(signup["email"], password)
            send(28084, "/v1/auth/logout", "POST", {}, cookie=cookie, csrf=customer["csrf_token"], expected=204)
            send(28081, "/v1/auth/me", token=customer["access_token"], expected=401)
            one, _ = login(signup["email"], password)
            two, _ = login(signup["email"], password)
            send(28084, "/v1/auth/logout-all", "POST", {}, token=one["access_token"], expected=204)
            send(28081, "/v1/auth/me", token=two["access_token"], expected=401)
            customer, cookie = login(signup["email"], password)
            with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
                def refresh():
                    req = urllib.request.Request("http://localhost:28084/v1/auth/refresh", method="POST", data=b"{}",
                                                 headers={"Content-Type": "application/json", "Origin": ORIGIN,
                                                          "Cookie": cookie, "X-CSRF-Token": customer["csrf_token"]})
                    try:
                        with urllib.request.urlopen(req, timeout=15) as response:
                            return response.status
                    except urllib.error.HTTPError as error:
                        return error.code
                assert sorted(pool.map(lambda _: refresh(), range(2))) == [200, 401]
            # A changed grant invalidates the prior access JWT immediately across all APIs.
            send(28084, "/v1/auth/admin/users/10/bindings", "PUT", {"roles": ["restaurant_staff"], "restaurant_ids": []}, token=at, expected=204)
            send(28081, "/restaurants/1/orders", token=st, expected=401)
            renewed, _ = login("staff@example.test", password)
            send(28081, "/restaurants/1/orders", token=renewed["access_token"], expected=403)
            send(28080, "/restaurants/1", "PATCH", {"name": "Forbidden"}, token=renewed["access_token"], expected=403)
            e.eventually(lambda: e.sql("notifications-postgres", "notifications", "notifications_service",
                                      f"SELECT is_active FROM device_registrations WHERE id={device['id']}") == "f")
            print("PASS: independent Auth, migration IDs, own login/register, JWT across four APIs, rotation/reuse/concurrency, logout/all, live grants, device revocation and CSRF.", flush=True)
        finally:
            e.compose("down", "-v", "--remove-orphans")


if __name__ == "__main__":
    main()
