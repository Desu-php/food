-- A reserved range avoids reusing historical IDs omitted from the old registry.
CREATE SEQUENCE auth_customer_ids START WITH 1000000000000;
CREATE TABLE auth_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000000) PRIMARY KEY,
    subject text NOT NULL UNIQUE CHECK(length(subject) BETWEEN 1 AND 255),
    email text UNIQUE CHECK(email IS NULL OR (email=lower(email) AND length(email)<=254)),
    password_hash text,
    status text NOT NULL CHECK(status IN ('ACTIVE','PENDING_VERIFICATION','DISABLED')),
    email_verified_at timestamptz,
    customer_id bigint UNIQUE CHECK(customer_id>0),
    roles text[] NOT NULL DEFAULT '{}',
    permissions text[] NOT NULL DEFAULT '{}',
    auth_version bigint NOT NULL DEFAULT 1 CHECK(auth_version>0),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK(roles <@ ARRAY['customer','restaurant_staff','courier','dispatcher','admin']::text[]),
    CHECK(permissions <@ ARRAY['delivery:dispatch','saga:retry']::text[]),
    CHECK(NOT ('customer'=ANY(roles)) OR customer_id IS NOT NULL),
    CHECK(status<>'ACTIVE' OR (email IS NOT NULL AND password_hash IS NOT NULL))
);
CREATE TABLE auth_restaurant_memberships (
    user_id bigint NOT NULL REFERENCES auth_users(id),
    restaurant_id bigint NOT NULL CHECK(restaurant_id>0),
    PRIMARY KEY(user_id,restaurant_id)
);
CREATE TABLE auth_courier_bindings (
    user_id bigint PRIMARY KEY REFERENCES auth_users(id),
    courier_id bigint NOT NULL UNIQUE CHECK(courier_id>0)
);
CREATE TABLE auth_sessions (
    id text PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES auth_users(id),
    auth_version bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    CHECK(expires_at>created_at)
);
CREATE INDEX auth_sessions_user ON auth_sessions(user_id,expires_at) WHERE revoked_at IS NULL;
CREATE INDEX auth_sessions_expiration ON auth_sessions(expires_at);
CREATE TABLE auth_refresh_tokens (
    token_hash text PRIMARY KEY CHECK(length(token_hash)=64),
    session_id text NOT NULL REFERENCES auth_sessions(id),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    consumed_at timestamptz
);
CREATE INDEX auth_refresh_session ON auth_refresh_tokens(session_id);
CREATE TABLE auth_rate_limits (
    key_hash text PRIMARY KEY,
    attempts integer NOT NULL,
    reset_at timestamptz NOT NULL
);
CREATE INDEX auth_rate_limits_reset ON auth_rate_limits(reset_at);
CREATE TABLE auth_legacy_identities (
    issuer text NOT NULL,
    subject text NOT NULL,
    user_id bigint NOT NULL UNIQUE REFERENCES auth_users(id),
    PRIMARY KEY(issuer,subject)
);
CREATE TABLE auth_audit (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    actor text NOT NULL,
    action text NOT NULL,
    user_id bigint REFERENCES auth_users(id),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE auth_device_revocations (
    user_id bigint PRIMARY KEY REFERENCES auth_users(id),
    not_after timestamptz NOT NULL DEFAULT clock_timestamp(),
    available_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    lease_token text,
    lease_until timestamptz,
    attempts integer NOT NULL DEFAULT 0
);
